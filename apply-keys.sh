        f'export CENSYS_API_SECRET="{get(keys, "censys", "secret")}"',
        f'export SECURITY_TRAILS_KEY="{get(keys, "securityTrails", "key")}"',
        f'export SECURITYTRAILS_API_KEY="{get(keys, "securityTrails", "key")}"',  # alias for osint.sh
        f'export VIRUSTOTAL_API_KEY="{get(keys, "virustotal", "key")}"',
