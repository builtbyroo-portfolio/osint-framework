    ]
    ENV_OUT.write_text("\n".join(lines) + "\n")
    print(f"  ✓ {ENV_OUT}")

def configure_shodan(keys):
    key = get(keys, "shodan", "key")
    if not key:
        print("  - shodan: no key set, skipping")
        return
    result = subprocess.run(["shodan", "init", key], capture_output=True, text=True)
    if result.returncode == 0:
        print("  ✓ shodan CLI configured")
    else:
        print(f"  ✗ shodan: {result.stderr.strip()}")

def configure_censys(keys):
    api_id     = get(keys, "censys", "id")
    api_secret = get(keys, "censys", "secret")
    if not api_id or not api_secret:
        print("  - censys: no id/secret set, skipping")
        return
    cfg_path = Path.home() / ".config" / "censys" / "censys.cfg"
    cfg_path.parent.mkdir(parents=True, exist_ok=True)
    cfg_path.write_text(
        f"[DEFAULT]\napi_id = {api_id}\napi_secret = {api_secret}\n"
    )
    print(f"  ✓ censys CLI configured ({cfg_path})")

def configure_nuclei(keys):
    pd_key = get(keys, "projectDiscovery", "key")
    if not pd_key:
        print("  - nuclei/pdcp: no ProjectDiscovery key set, skipping")
        return
    cfg_path = Path.home() / ".pdcp" / "credentials.yaml"
    cfg_path.parent.mkdir(parents=True, exist_ok=True)
    cfg_path.write_text(f"api-key: {pd_key}\n")
    print(f"  ✓ ProjectDiscovery Cloud credentials saved ({cfg_path})")

def main():
    if not KEYS_YAML.exists():
        print(f"ERROR: {KEYS_YAML} not found")
        sys.exit(1)

    keys = load_keys()
    filled = sum(1 for v in keys.values()
                 if isinstance(v, dict) and any(str(x).strip() for x in v.values() if x))
    total  = len(keys)
    print(f"\napply-keys — {filled}/{total} keys populated\n")

    print("Generating ~/.config/osint/keys.env ...")
    write_env(keys)

    print("Configuring shodan CLI ...")
    configure_shodan(keys)

    print("Configuring censys CLI ...")
    configure_censys(keys)

    print("Configuring nuclei / ProjectDiscovery Cloud ...")
    configure_nuclei(keys)

    print(f"\nDone. Re-source your shell or run:\n  source {ENV_OUT}\n")

if __name__ == "__main__":
    main()
