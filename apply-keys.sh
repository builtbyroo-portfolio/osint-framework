#!/usr/bin/env python3
"""
apply-keys.sh — propagates API keys from ~/.theHarvester/api-keys.yaml to:
  - ~/.config/osint/keys.env      (bash exports — sourced at shell startup)
  - shodan CLI                     (shodan init KEY)
  - censys CLI                     (~/.config/censys/censys.cfg)
  - nuclei                         (~/.config/nuclei/nuclei-config.yaml)
  - ProjectDiscovery Cloud (pdcp)  (~/.pdcp/credentials.yaml)

Run this any time you update ~/.theHarvester/api-keys.yaml
"""
import sys
import os
import subprocess
from pathlib import Path

try:
    import yaml
except ImportError:
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", "pyyaml"], check=True)
    import yaml

KEYS_YAML = Path.home() / ".theHarvester" / "api-keys.yaml"
ENV_OUT   = Path.home() / ".config" / "osint" / "keys.env"

def load_keys():
    with open(KEYS_YAML) as f:
        data = yaml.safe_load(f)
    return data.get("apikeys", {})

def get(keys, *path, default=""):
    d = keys
    for p in path:
        if not isinstance(d, dict):
            return default
        d = d.get(p, {})
    return d if isinstance(d, str) and d.strip() else default

def write_env(keys):
    ENV_OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
